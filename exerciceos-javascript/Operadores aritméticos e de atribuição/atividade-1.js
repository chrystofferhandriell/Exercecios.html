let a = 10;
let b = 5;

// Adição
let soma = a + b;        // 15

// Subtração
let subtracao = a - b;  // 5

// Multiplicação
let multiplicacao = a * b; // 50

// Divisão
let divisao = a / b;    // 2

// Resto da divisão (módulo)
let resto = a % b;      // 0

// Incremento
a++; // a = 11

// Decremento
b--; // b = 4

console.log(soma);
console.log(subtracao);
console.log(multiplicacao);
console.log(divisao);
console.log(resto);
console.log(a);
console.log(b);